"""Unit tests for themes.utils.frappe_ui_bridge (no Frappe bench)."""
from __future__ import annotations

import unittest

from themes.utils.frappe_ui_bridge import BRIDGE_SELECTOR, generate_bridge_css


class TestFrappeUiBridge(unittest.TestCase):
	def test_selector_excludes_dark(self) -> None:
		css = generate_bridge_css({"primary_color": "#336699"})
		self.assertIn(BRIDGE_SELECTOR, css)
		self.assertIn(':not(.dark)', css)
		self.assertIn(':not([data-theme="dark"])', css)

	def test_gray_and_blue_map_to_nce_vars(self) -> None:
		css = generate_bridge_css({"primary_color": "#336699"})
		self.assertIn("--gray-500: var(--nce-color-neutral-500);", css)
		self.assertIn("--blue-500: var(--nce-color-primary-500);", css)

	def test_unconfigured_danger_emits_no_red(self) -> None:
		css = generate_bridge_css({"primary_color": "#336699"})
		self.assertNotRegex(css, r"--red-\d+:")

	def test_no_hardcoded_nce_hex_values(self) -> None:
		css = generate_bridge_css({
			"primary_color": "#336699",
			"danger_color": "#CC0000",
		})
		self.assertNotRegex(css, r"--nce-color-[a-z-]+:\s*#")

	def test_neutral_only_without_brand_colors(self) -> None:
		css = generate_bridge_css({})
		self.assertIn("Generated by themes.utils.frappe_ui_bridge", css)
		self.assertIn("--gray-500: var(--nce-color-neutral-500);", css)
		self.assertNotIn("--blue-500:", css)

	def test_danger_via_shades_only(self) -> None:
		css = generate_bridge_css({
			"primary_color": "#336699",
			"danger_color_shades": '{"500": "#ef4444"}',
		})
		self.assertIn("--red-500: var(--nce-color-danger-500);", css)


if __name__ == "__main__":
	unittest.main()
