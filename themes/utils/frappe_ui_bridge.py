"""Frappe UI raw palette bridge: remap Espresso --gray-* / --blue-* from NCE theme tokens."""
from __future__ import annotations

BRIDGE_SELECTOR = ':root[data-nce-bridge="on"]:not(.dark):not([data-theme="dark"])'

FRAPPE_UI_SHADES = (50, 100, 200, 300, 400, 500, 600, 700, 800, 900)

# Frappe CSS family -> (theme_json colour field, --nce-color-<role> prefix)
FAMILY_ROLE_MAP: dict[str, tuple[str, str]] = {
    "gray": ("neutral_color", "color-neutral"),
    "blue": ("primary_color", "color-primary"),
    "red": ("danger_color", "color-danger"),
    "green": ("success_color", "color-success"),
    "orange": ("warning_color", "color-warning"),
    "amber": ("warning_color", "color-warning"),
    "cyan": ("info_color", "color-info"),
}

_BRIDGE_HEADER = (
    "/* Generated by themes.utils.frappe_ui_bridge — do not edit.\n"
    " * Remaps Frappe UI Espresso raw palette (--gray-*, --blue-*, …) from NCE theme\n"
    " * tokens when <html data-nce-bridge=\"on\"> (light mode only).\n"
    " */\n"
)


def bridge_css_declarations(payload: dict) -> list[str]:
    """Return --gray-* / --blue-* declaration lines for a theme payload (shared by publish and export)."""
    from themes.utils.css_writer import _role_is_configured

    g = payload.get
    declarations: list[str] = []
    configured_fields = {
        field
        for field in {pair[0] for pair in FAMILY_ROLE_MAP.values()}
        if _role_is_configured(g, field)
    }

    for family, (field, nce_prefix) in FAMILY_ROLE_MAP.items():
        if field not in configured_fields:
            continue
        for shade in FRAPPE_UI_SHADES:
            declarations.append(
                f"\t--{family}-{shade}: var(--nce-{nce_prefix}-{shade});"
            )
    return declarations


def generate_bridge_css_block(payload: dict, selector: str) -> str:
    """Build one bridge rule block for selector (no file header)."""
    declarations = bridge_css_declarations(payload)
    if not declarations:
        return ""
    return f"{selector} {{\n" + "\n".join(declarations) + "\n}\n"


def generate_bridge_css(payload: dict) -> str:
    """Build bridge CSS for configured colour roles only."""
    declarations = bridge_css_declarations(payload)
    if not declarations:
        return _BRIDGE_HEADER

    block = generate_bridge_css_block(payload, BRIDGE_SELECTOR)
    return _BRIDGE_HEADER + block


def publish_frappe_ui_bridge_css(payload: dict) -> str:
    """Write nce_frappe_ui_bridge.css and sidecar; return hash (no DB field, no cache bust)."""
    from themes.utils.css_publish import write_published_css

    css = generate_bridge_css(payload)
    return write_published_css("nce_frappe_ui_bridge.css", css)
