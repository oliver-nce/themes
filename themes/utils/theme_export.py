EXPORT_ROOT = "nce-themes"
DEVELOPER_EXPORT_GUIDE_FILENAME = "Themes_Developer_Export_Guide.pdf"


def _developer_export_guide_source_path() -> str:
    module_dir = os.path.dirname(os.path.abspath(__file__))
    return os.path.normpath(
        os.path.join(
            module_dir,
            "..",
            "public",
            "docs",
            DEVELOPER_EXPORT_GUIDE_FILENAME,
        )
    )


def _read_developer_export_guide_bytes() -> bytes | None:
    path = _developer_export_guide_source_path()
    if not os.path.isfile(path):
        return None
    with open(path, "rb") as fh:
        return fh.read()
EXPORT_FONT_URL_BASE = "fonts"
EXPORT_BRIDGE_SELECTOR = (
    ':where(:root[data-nce-bridge="on"]:not(.dark):not([data-theme="dark"]))'
)


class ThemeExportError(ValueError):
    """Invalid export inputs (missing slug, unknown theme, etc.)."""


def _item_by_name(items: list[dict[str, Any]], name: str) -> dict[str, Any]:
    for item in items:
        if item["name"] == name:
            return item
    raise ThemeExportError(f"Unknown theme: {name}")


def validate_export_items(items: list[dict[str, Any]], default_name: str) -> None:
    """Ensure default exists and every non-default theme has a slug."""
    _item_by_name(items, default_name)
    missing_slug = [
        item.get("theme_name") or item["name"]
        for item in items
        if item["name"] != default_name and not (item.get("slug") or "").strip()
    ]
    if missing_slug:
        raise ThemeExportError(
            "These themes need a slug before export: " + ", ".join(missing_slug)
        )


def _theme_display_names(items: list[dict[str, Any]]) -> list[str]:
    return [item.get("theme_name") or item["name"] for item in items]


def build_export_css(
    items: list[dict[str, Any]],
    default_name: str,
    include_bridge: bool = False,
) -> str:
    """Build nce-themes.css content (no custom CSS on the default theme)."""
    validate_export_items(items, default_name)
    default_item = _item_by_name(items, default_name)
    default_payload = default_item["payload"]
    other_items = [i for i in items if i["name"] != default_name]

    g = default_payload.get
    lines: list[str] = []
    generated = date.today().isoformat()
    names_line = ", ".join(_theme_display_names(items))
    lines.append(
        f"/* NCE Themes developer export — {generated}\n"
        f" * Themes: {names_line}\n"
        " * Generated by the Themes app — snapshot, re-export to update.\n"
        " */"
    )
    lines.append("")

    all_payloads = [default_payload] + [i["payload"] for i in other_items]
    _emit_font_faces_multi(all_payloads, lines, font_base_url=EXPORT_FONT_URL_BASE)

    _emit_var_block(g, lines, ":where(:root)", include_custom_css=False)
    _emit_role_bg_classes(g, lines)
    _emit_role_text_border_classes(g, lines)
    _emit_role_shade_classes(g, lines)
    _emit_neutral_classes(g, lines)
    _emit_table_classes(lines)
    _emit_shape_classes(lines)
    _emit_typography_classes(g, lines)
    _emit_spacing_classes(lines)
    _emit_bg_themed(lines)

    for item in other_items:
        slug = (item.get("slug") or "").strip()
        _emit_var_block(
            item["payload"].get,
            lines,
            f':where([data-nce-theme="{slug}"])',
            include_custom_css=False,
        )

    if include_bridge:
        bridge = generate_bridge_css_block(default_payload, EXPORT_BRIDGE_SELECTOR)
        if bridge:
            lines.append("")
            lines.append("/* Frappe UI Espresso palette bridge (light mode, data-nce-bridge=\"on\") */")
            lines.append(bridge.rstrip())

    return "\n".join(lines) + "\n"


def _font_files_for_payloads(
    payloads: list[dict],
    fonts_dir: Path,
) -> dict[str, bytes]:
    """Map zip-relative font paths to file bytes for fonts referenced by payloads."""
    names = _collect_font_names(payloads)
    out: dict[str, bytes] = {}
    for name in names:
        entry = FONT_REGISTRY.get(name)
        if not entry:
            continue
        slug = entry[0]
        for subset in FONT_SUBSETS:
            filename = f"{subset}-wght-normal.woff2"
            src = fonts_dir / slug / filename
            if not src.is_file():
                continue
            rel = f"{EXPORT_ROOT}/fonts/{slug}/{filename}"
            out[rel] = src.read_bytes()
    return out


def build_export_js(items: list[dict[str, Any]], default_name: str) -> str:
    """Tiny theme switcher for document.documentElement data-nce-theme."""
    validate_export_items(items, default_name)
    themes_meta = []
    for item in items:
        is_default = item["name"] == default_name
        slug = "" if is_default else (item.get("slug") or "").strip()
        label = item.get("theme_name") or item["name"]
        themes_meta.append({"slug": slug, "name": label})
    meta_json = json.dumps(themes_meta, ensure_ascii=False)
    return f"""/* NCE theme switcher — dependency-free snapshot helper.
 * If the Themes app is installed on this site, pick themes there instead.
 */
(function () {{
  var STORAGE_KEY = "nce-theme";
  window.nceThemes = {meta_json};

  function apply(slug) {{
    var root = document.documentElement;
    if (slug) {{
      root.setAttribute("data-nce-theme", slug);
      try {{ localStorage.setItem(STORAGE_KEY, slug); }} catch (e) {{}}
    }} else {{
      root.removeAttribute("data-nce-theme");
      try {{ localStorage.removeItem(STORAGE_KEY); }} catch (e) {{}}
    }}
  }}

  window.nceSetTheme = function (slug) {{
    slug = (slug || "").trim();
    apply(slug);
  }};

  var stored = "";
  try {{ stored = localStorage.getItem(STORAGE_KEY) || ""; }} catch (e) {{}}
  if (stored) {{
    var known = window.nceThemes.some(function (t) {{ return t.slug === stored; }});
    if (known) {{
      apply(stored);
    }}
  }}
}})();
"""


def build_export_readme(
    items: list[dict[str, Any]],
    default_name: str,
    include_bridge: bool,
    app_name_hint: str = "your_app",
) -> str:
    """Plain-language install steps for developers."""
    validate_export_items(items, default_name)
    lines = [
        "NCE Themes — developer export",
        "================================",
        "",
        "Full step-by-step guide: Themes_Developer_Export_Guide.pdf (in this folder).",
        "",
        "This folder is a snapshot from the Themes app. Re-export from Themes to pick up edits.",
        "",
        "1) Copy the nce-themes folder into your Frappe app's public folder, for example:",
        f"   <app>/public/nce-themes/",
        "",
        "2) Include the CSS and JS on your app's screens (hooks.py example):",
        "",
        "   app_include_css = [",
        f'       "/assets/{app_name_hint}/nce-themes/nce-themes.css",',
        "   ]",
        "   app_include_js = [",
        f'       "/assets/{app_name_hint}/nce-themes/nce-theme-switcher.js",',
        "   ]",
        "",
        "   Or add the same URLs in your own HTML templates.",
        "",
        "3) Let end users pick a theme in the browser:",
        "",
        '   nceSetTheme("ocean");   // slug from the list below',
        '   nceSetTheme("");        // back to the default (:root) theme',
        "",
        "4) Exported themes and slugs:",
        "",
    ]
    for item in items:
        label = item.get("theme_name") or item["name"]
        if item["name"] == default_name:
            lines.append(f'   - {label}  (default, slug "")')
        else:
            slug = (item.get("slug") or "").strip()
            lines.append(f'   - {label}  (slug "{slug}")')
    lines.append("")
    if include_bridge:
        lines.extend(
            [
                "5) Frappe UI colour mapping is included in nce-themes.css.",
                "   On app screens where you want Espresso greys/blues to follow NCE tokens, set on",
                '   the browser top-level <html> element: data-nce-bridge="on" (light mode only).',
                "",
            ]
        )
    lines.extend(
        [
            "Notes:",
            "- Fonts used by these themes are bundled under fonts/.",
            "- If the Themes app is installed on the same site, its published theme CSS wins over",
            "  this snapshot (export selectors use :where() for lower specificity).",
            "",
        ]
    )
    return "\n".join(lines)


def build_export_files(
    items: list[dict[str, Any]],
    default_name: str,
    include_bridge: bool = False,
    fonts_dir: Path | None = None,
) -> dict[str, bytes]:
    """Return zip member path → bytes for the full nce-themes/ tree."""
    validate_export_items(items, default_name)
    default_item = _item_by_name(items, default_name)
    all_payloads = [default_item["payload"]] + [
        i["payload"] for i in items if i["name"] != default_name
    ]

    files: dict[str, bytes] = {}
    css = build_export_css(items, default_name, include_bridge=include_bridge)
    files[f"{EXPORT_ROOT}/nce-themes.css"] = css.encode("utf-8")
    files[f"{EXPORT_ROOT}/nce-theme-switcher.js"] = build_export_js(
        items, default_name
    ).encode("utf-8")
    files[f"{EXPORT_ROOT}/README.txt"] = build_export_readme(
        items, default_name, include_bridge
    ).encode("utf-8")

    guide_bytes = _read_developer_export_guide_bytes()
    if guide_bytes is not None:
        files[f"{EXPORT_ROOT}/{DEVELOPER_EXPORT_GUIDE_FILENAME}"] = guide_bytes

    if fonts_dir is not None:
        files.update(_font_files_for_payloads(all_payloads, fonts_dir))

    return files


def build_export_zip(files: dict[str, bytes]) -> bytes:
    """Pack export files into a zip archive (paths as given)."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for path, data in sorted(files.items()):
            zf.writestr(path, data)
    return buf.getvalue()


def export_bundle_filename() -> str:
    return f"nce-themes-{date.today().strftime('%Y%m%d')}.zip"


def _load_theme_rows(theme_names: list[str]) -> list[dict[str, Any]]:
    import frappe

    rows: list[dict[str, Any]] = []
    for name in theme_names:
        if not frappe.db.exists("NCE Theme", name):
            frappe.throw(f"Unknown NCE Theme: {name}")
        theme_name, slug, theme_json = frappe.db.get_value(
            "NCE Theme",
            name,
            ["theme_name", "slug", "theme_json"],
        )
        payload = json.loads(theme_json or "{}")
        rows.append(
            {
                "name": name,
                "theme_name": theme_name,
                "slug": (slug or "").strip(),
                "payload": payload,
            }
        )
    return rows


def export_bundle_for(
    theme_names: list[str],
    default_theme: str | None = None,
    include_bridge: bool = False,
) -> tuple[str, bytes]:
    """Load themes from DB, build zip bytes, return (filename, zip_bytes)."""
    import frappe

    if not theme_names:
        frappe.throw("Select at least one theme to export")
    if isinstance(theme_names, str):
        theme_names = frappe.parse_json(theme_names)
    theme_names = list(theme_names)
    default_name = default_theme or theme_names[0]
    if default_name not in theme_names:
        frappe.throw(f"Default theme must be one of the exported themes: {default_name}")

    items = _load_theme_rows(theme_names)
    try:
        validate_export_items(items, default_name)
    except ThemeExportError as exc:
        frappe.throw(str(exc))

    fonts_dir = Path(frappe.get_app_path("themes")) / "public" / "fonts"
    files = build_export_files(
        items,
        default_name,
        include_bridge=bool(include_bridge),
        fonts_dir=fonts_dir,
    )
    return export_bundle_filename(), build_export_zip(files)


def list_export_theme_rows() -> list[dict]:
    """All NCE Theme rows for the export checklist (no desk family)."""
    import frappe
    rows = frappe.get_all(
        "NCE Theme",
        fields=["name", "theme_name", "slug", "status"],
        order_by="theme_name asc",
    )
    for row in rows:
        row["slug"] = (row.get("slug") or "").strip()
    return rows
