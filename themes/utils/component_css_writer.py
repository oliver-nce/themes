def _important(decls: list[str]) -> list[str]:
	out: list[str] = []
	for decl in decls:
		if "!important" in decl:
			out.append(decl)
			continue
		trimmed = decl.rstrip()
		if trimmed.endswith(";"):
			out.append(f"{trimmed[:-1]} !important;")
		else:
			out.append(f"{trimmed} !important;")
	return out


def _row_value(row, key):
	return row.get(key) if isinstance(row, dict) else getattr(row, key, None)


def _valid_text_override(row: dict) -> bool:
	cls = (row.get("override_text_class") or "").strip()
	return bool(cls and TEXT_RE.match(cls))


def _button_size_decls(size_cls: str) -> list[str]:
	prefix = BUTTON_SIZE_CLASSES.get(size_cls)
	if not prefix:
		return []
	return [
		f"font-size: var(--nce-btn-{prefix}-font-size);",
		f"padding: var(--nce-btn-{prefix}-pad-y) var(--nce-btn-{prefix}-pad-x);",
		f"min-height: var(--nce-btn-{prefix}-min-height);",
		"line-height: 1.4;",
		"box-sizing: border-box;",
	]


def _legacy_declarations_for(row: dict) -> list[str]:
	"""Pre-catalog override fields (used when no style overrides apply)."""
	decls: list[str] = []
	text_override = _valid_text_override(row)

	bg_cls = (row.get("override_bg_class") or "").strip()
	bg_match = BG_RE.match(bg_cls) if bg_cls else None
	if bg_match:
		role, shade = bg_match.group(1), bg_match.group(2)
		v = f"--nce-color-{role}-{shade}" if shade else f"--nce-color-{role}"
		decls.append(f"background-color: var({v});")
		if not text_override:
			fg_suffix = "-fg-tonal" if (row.get("override_fg_type") or "").strip() == "tonal" else "-fg"
			decls.append(f"color: var({v}{fg_suffix});")

	text_cls = (row.get("override_text_class") or "").strip()
	if text_cls and TEXT_RE.match(text_cls):
		rest = text_cls[len("theme-text-"):]
		decls.append(f"color: var(--nce-color-{rest});")

	width_cls = (row.get("override_border_width_class") or "").strip()
	if width_cls in BORDER_WIDTHS:
		decls.append("border-style: solid;")
		decls.append(f"border-width: var({BORDER_WIDTHS[width_cls]});")

	border_cls = (row.get("override_border_color_class") or "").strip()
	border_match = BORDER_COLOR_RE.match(border_cls) if border_cls else None
	if border_match:
		role, shade = border_match.group(1), border_match.group(2)
		decls.append(f"border-color: var(--nce-color-{role}-{shade});")

	size_cls = normalize_button_size_class(row.get("override_button_size_class") or "")
	decls.extend(_button_size_decls(size_cls))

	return decls


def declaration_blocks_for(row: dict) -> list[tuple[str | None, list[str]]]:
	if effective_style_overrides(row):
		return override_declaration_blocks(row)
	legacy = _legacy_declarations_for(row)
	if legacy:
		return [(None, legacy)]
	return []


def declarations_for(row: dict) -> list[str]:
	decls: list[str] = []
	for pseudo, block in declaration_blocks_for(row):
		if pseudo:
			continue
		decls.extend(block)
	return decls


def preview_css_for_selector(selector: str, row: dict) -> str:
	"""Full preview CSS including :hover rules (Design Mode live preview)."""
	from themes.utils.instance_style import preview_css_for_instance

	triple = f".{selector}.{selector}.{selector}.{selector}"
	chunks: list[str] = []
	for pseudo, block in declaration_blocks_for(row):
		if not block:
			continue
		chunks.append(f"{triple}{pseudo or ''} {{ {' '.join(block)} }}")
	base = " ".join(chunks)
	instance_id = (row.get("instance_id") or "").strip()
	instance_sparse = row.get("instance_style_overrides")
	if instance_id and instance_sparse:
		inst = preview_css_for_instance(selector, instance_id, row, instance_sparse)
		if inst:
			return (base + " " + inst).strip()
	return base


def _table_bg_decls(bg_cls: str, fg_type: str) -> list[str]:
	bg_match = BG_RE.match(bg_cls) if bg_cls else None
	if not bg_match:
		return []
	role, shade = bg_match.group(1), bg_match.group(2)
	v = f"--nce-color-{role}-{shade}" if shade else f"--nce-color-{role}"
	fg_suffix = "-fg-tonal" if fg_type == "tonal" else "-fg"
	return [
		f"background-color: var({v});",
		f"color: var({v}{fg_suffix});",
	]


def _table_border_value(width_cls: str, color_cls: str, default_width_var: str, default_color_var: str) -> str | None:
	width_var = None
	if width_cls in BORDER_WIDTHS:
		width_var = BORDER_WIDTHS[width_cls]
	elif color_cls and BORDER_COLOR_RE.match(color_cls):
		width_var = default_width_var

	color_var = None
	border_match = BORDER_COLOR_RE.match(color_cls) if color_cls else None
	if border_match:
		role, shade = border_match.group(1), border_match.group(2)
		color_var = f"--nce-color-{role}-{shade}"
	elif width_cls in BORDER_WIDTHS:
		color_var = default_color_var

	if not width_var or not color_var:
		return None
	return f"var({width_var}) solid var({color_var})"


def _bundle_selectors(target: str) -> tuple[str, str] | None:
	"""(strong, weak) selector prefixes for one theme_table_targets line."""
	kind, _, name = (target or "").strip().partition(":")
	name = name.strip()
	if not name or not SELECTOR_RE.match(name):
		return None
	if kind == "class":
		return (f".{name}.{name}.{name}", f".{name}")
	if kind == "scope":
		return (f".{name}.{name}.{name} table", f".{name} table")
	return None


def theme_table_bundle_for(parent: dict) -> str:
	"""The theme-table rules, aimed at this component's tables that do not carry theme-table."""
	if (parent.get("status") or "").strip() != "Present":
		return ""
	blocks: list[str] = []
	for line in (parent.get("theme_table_targets") or "").splitlines():
		pair = _bundle_selectors(line)
		if not pair:
			continue
		strong, weak = pair
		col = "var(--nce-border-width-table-col) solid var(--nce-color-table-col-divider)"
		row = "var(--nce-border-width-table-row) solid var(--nce-color-table-row-divider)"
		blocks.append("\n".join([
			f"/* {parent.get('component_name') or ''} › theme table {line.strip()} */",
			f"{strong} {{\n\tborder-collapse: collapse;\n}}",
			f"{strong} thead th, {strong} tfoot th, {strong} tfoot td {{\n\tbackground-color: var(--nce-color-table-header);\n\tcolor: var(--nce-color-table-header-fg, var(--nce-color-text));\n}}",
			f"{weak} tbody tr:nth-child(even) {{\n\tbackground-color: var(--nce-color-row);\n}}",
			f"{weak} tbody tr:nth-child(odd) {{\n\tbackground-color: var(--nce-color-row-alt);\n}}",
			f"{strong} td {{\n\tborder-bottom: {row};\n\tborder-right: {col};\n}}",
			f"{strong} th {{\n\tborder-right: {col};\n}}",
			f"{strong} th:last-child, {strong} td:last-child {{\n\tborder-right: none;\n}}",
		]))
	return "\n\n".join(blocks)


def _table_prefix(parent: dict) -> str | None:
	sel = (parent.get("table_selector") or "").strip()
	scope = (parent.get("table_scope_class") or "").strip()
	if not sel or not SELECTOR_RE.match(sel):
		return None
	if scope and not SELECTOR_RE.match(scope):
		return None
	if scope:
		return f".{scope}.{scope}.{scope} .{sel}"
	return f".{sel}.{sel}.{sel}"


def table_css_for(parent: dict) -> str:
	if (parent.get("status") or "").strip() != "Present":
		return ""
	if not int(parent.get("has_table") or 0):
		return ""
	prefix = _table_prefix(parent)
	if not prefix:
		return ""

	component_name = parent.get("component_name") or ""
	sel = (parent.get("table_selector") or "").strip()
	scope = (parent.get("table_scope_class") or "").strip()
	row_prefix = f".{scope} .{sel}" if scope else f".{sel}"
	rules: list[str] = []

	header_bg = (parent.get("table_header_bg_class") or "").strip()
	header_fg = (parent.get("table_header_fg_type") or "mono").strip() or "mono"
	header_decls = _table_bg_decls(header_bg, header_fg)
	if header_decls:
		target = f"{prefix} thead th, {prefix} tfoot th, {prefix} tfoot td"
		rules.append(target + " {\n\t" + "\n\t".join(header_decls) + "\n}")

	row_bg = (parent.get("table_row_bg_class") or "").strip()
	row_fg = (parent.get("table_row_fg_type") or "mono").strip() or "mono"
	row_decls = _table_bg_decls(row_bg, row_fg)
	if row_decls:
		target = f"{row_prefix} tbody tr:nth-child(even)"
		rules.append(target + " {\n\t" + "\n\t".join(row_decls) + "\n}")

	alt_bg = (parent.get("table_row_alt_bg_class") or "").strip()
	alt_fg = (parent.get("table_row_alt_fg_type") or "mono").strip() or "mono"
	alt_decls = _table_bg_decls(alt_bg, alt_fg)
	if alt_decls:
		target = f"{row_prefix} tbody tr:nth-child(odd)"
		rules.append(target + " {\n\t" + "\n\t".join(alt_decls) + "\n}")

	header_line_w = (parent.get("table_header_line_class") or "").strip()
	header_line_c = (parent.get("table_header_line_color_class") or "").strip()
	header_border = _table_border_value(
		header_line_w,
		header_line_c,
		"--nce-border-width-table-row",
		"--nce-color-table-row-divider",
	)
	if header_border:
		rules.append(f"{prefix} thead th {{\n\tborder-bottom: {header_border};\n}}")

	row_div_w = (parent.get("table_row_divider_class") or "").strip()
	row_div_c = (parent.get("table_row_divider_color_class") or "").strip()
	row_border = _table_border_value(
		row_div_w,
		row_div_c,
		"--nce-border-width-table-row",
		"--nce-color-table-row-divider",
	)
	if row_border:
		rules.append(f"{prefix} td {{\n\tborder-bottom: {row_border};\n}}")

	col_div_w = (parent.get("table_col_divider_class") or "").strip()
	col_div_c = (parent.get("table_col_divider_color_class") or "").strip()
	col_border = _table_border_value(
		col_div_w,
		col_div_c,
		"--nce-border-width-table-col",
		"--nce-color-table-col-divider",
	)
	if col_border:
		rules.append(f"{prefix} th, {prefix} td {{\n\tborder-right: {col_border};\n}}")
		rules.append(
			f"{prefix} th:last-child, {prefix} td:last-child {{\n\tborder-right: none;\n}}"
		)

	if not rules:
		return ""
	return f"/* {component_name} › table {sel} */\n" + "\n\n".join(rules)


def _table_prefixes_with_instance(parent: dict, instance_id: str) -> tuple[str | None, str]:
	sel = (parent.get("table_selector") or "").strip()
	scope = (parent.get("table_scope_class") or "").strip()
	iid = (instance_id or "").strip()
	if not sel or not SELECTOR_RE.match(sel) or not iid:
		return None, ""
	if scope and not SELECTOR_RE.match(scope):
		return None, ""
	inst = f'[{INSTANCE_ATTR}="{iid}"]'
	if scope:
		prefix = f".{scope}.{scope}.{scope} .{sel}.{sel}.{sel}{inst}"
		row_prefix = f".{scope} .{sel}"
	else:
		prefix = f".{sel}.{sel}.{sel}{inst}"
		row_prefix = f".{sel}"
	return prefix, row_prefix


def _parent_with_table_overrides(parent: dict, sparse: dict[str, str]) -> dict:
	merged = dict(parent)
	resolved = effective_style_overrides(parent)
	resolved.update({k: v for k, v in sparse.items() if k in TABLE_PROPERTY_ID_SET})
	for prop_id, value in resolved.items():
		if prop_id not in TABLE_PROPERTY_ID_SET:
			continue
		from themes.utils.theme_class_catalog import PROPERTIES

		field = (PROPERTIES.get(prop_id) or {}).get("legacyField")
		if field:
			merged[field] = (value or "").strip()
	return merged


def table_instance_css_for(parent: dict, instance_id: str, sparse: dict[str, str]) -> str:
	"""CSS for sparse table instance overrides (data-nce-instance on the table element)."""
	if not sparse:
		return ""
	touched = {k for k in sparse if is_table_property_id(k)}
	if not touched:
		return ""
	prefix, row_prefix = _table_prefixes_with_instance(parent, instance_id)
	if not prefix:
		return ""
	row = _parent_with_table_overrides(parent, sparse)
	rules: list[str] = []

	if PROP_TABLE_HEADER_ROW in touched:
		header_bg = (row.get("table_header_bg_class") or "").strip()
		header_fg = (row.get("table_header_fg_type") or "mono").strip() or "mono"
		header_decls = _table_bg_decls(header_bg, header_fg)
		if header_decls:
			target = f"{prefix} thead th, {prefix} tfoot th, {prefix} tfoot td"
			rules.append(target + " {\n\t" + "\n\t".join(header_decls) + "\n}")

	if PROP_TABLE_ROWS in touched:
		row_bg = (row.get("table_row_bg_class") or "").strip()
		row_fg = (row.get("table_row_fg_type") or "mono").strip() or "mono"
		row_decls = _table_bg_decls(row_bg, row_fg)
		if row_decls:
			target = f"{prefix} tbody tr:nth-child(even)"
			rules.append(target + " {\n\t" + "\n\t".join(row_decls) + "\n}")

	if PROP_TABLE_ALT_ROWS in touched:
		alt_bg = (row.get("table_row_alt_bg_class") or "").strip()
		alt_fg = (row.get("table_row_alt_fg_type") or "mono").strip() or "mono"
		alt_decls = _table_bg_decls(alt_bg, alt_fg)
		if alt_decls:
			target = f"{prefix} tbody tr:nth-child(odd)"
			rules.append(target + " {\n\t" + "\n\t".join(alt_decls) + "\n}")

	if {PROP_TABLE_HEADER_LINE_W, PROP_TABLE_HEADER_LINE_C} & touched:
		header_line_w = (row.get("table_header_line_class") or "").strip()
		header_line_c = (row.get("table_header_line_color_class") or "").strip()
		header_border = _table_border_value(
			header_line_w,
			header_line_c,
			"--nce-border-width-table-row",
			"--nce-color-table-row-divider",
		)
		if header_border:
			rules.append(f"{prefix} thead th {{\n\tborder-bottom: {header_border};\n}}")

	if {PROP_TABLE_ROW_DIV_W, PROP_TABLE_ROW_DIV_C} & touched:
		row_div_w = (row.get("table_row_divider_class") or "").strip()
		row_div_c = (row.get("table_row_divider_color_class") or "").strip()
		row_border = _table_border_value(
			row_div_w,
			row_div_c,
			"--nce-border-width-table-row",
			"--nce-color-table-row-divider",
		)
		if row_border:
			rules.append(f"{prefix} td {{\n\tborder-bottom: {row_border};\n}}")

	if {PROP_TABLE_COL_DIV_W, PROP_TABLE_COL_DIV_C} & touched:
		col_div_w = (row.get("table_col_divider_class") or "").strip()
		col_div_c = (row.get("table_col_divider_color_class") or "").strip()
		col_border = _table_border_value(
			col_div_w,
			col_div_c,
			"--nce-border-width-table-col",
			"--nce-color-table-col-divider",
		)
		if col_border:
			rules.append(f"{prefix} th, {prefix} td {{\n\tborder-right: {col_border};\n}}")
			rules.append(
				f"{prefix} th:last-child, {prefix} td:last-child {{\n\tborder-right: none;\n}}"
			)

	if not rules:
		return ""
	component_name = parent.get("component_name") or ""
	sel = (parent.get("table_selector") or "").strip()
	return f"/* instance › {component_name} › table {sel} › {instance_id} */\n" + "\n\n".join(rules)


def preview_table_css(parent: dict, instance_id: str | None = None, instance_sparse=None) -> str:
	"""Live preview for Design Mode table popup (component + optional instance layer)."""
	base = table_css_for(parent)
	if not instance_id or not instance_sparse:
		return base
	from themes.utils.instance_style import parse_instance_style_overrides

	sparse = parse_instance_style_overrides(instance_sparse)
	inst = table_instance_css_for(parent, instance_id, sparse)
	if base and inst:
		return base + "\n\n" + inst
	return inst or base


def generate_component_css(rows: list[dict]) -> str:
	eligible: list[dict] = []
	for row in rows:
		if row.get("element_status") != "Present":
			continue
		if row.get("keep_default"):
			continue
		selector = (row.get("selector_class") or "").strip()
		if not SELECTOR_RE.match(selector):
			continue
		if not has_override(row):
			continue
		eligible.append(row)

	by_rule: dict[tuple[str, str], dict] = {}
	for row in eligible:
		key = (row.get("component_name") or "", (row.get("selector_class") or "").strip())
		if key not in by_rule or int(row.get("line") or 0) < int(by_rule[key].get("line") or 0):
			by_rule[key] = row

	sorted_rows = sorted(by_rule.values(), key=lambda r: (r.get("component_name") or "", (r.get("selector_class") or "").strip()))
	rows_by_selector: dict[str, dict] = {}
	for row in rows:
		if row.get("element_status") != "Present":
			continue
		sel = (row.get("selector_class") or "").strip()
		if sel and sel not in rows_by_selector:
			rows_by_selector[sel] = row
	rule_blocks: list[str] = []
	for row in sorted_rows:
		blocks = declaration_blocks_for(row)
		if not blocks:
			continue
		c = (row.get("selector_class") or "").strip()
		component_name = row.get("component_name") or ""
		prefix = f".{c}.{c}.{c}"
		chunk_lines = [f"/* {component_name} › {c} */"]
		for pseudo, decls in blocks:
			if not decls:
				continue
			if row.get("override_important"):
				decls = _important(decls)
			chunk_lines.append(f"{prefix}{pseudo or ''} {{")
			for decl in decls:
				chunk_lines.append(f"\t{decl}")
			chunk_lines.append("}")
		rule_blocks.append("\n".join(chunk_lines))

	if not rule_blocks:
		element_body = ""
	else:
		element_body = "\n\n".join(rule_blocks)

	instance_blocks = generate_instance_css(rows_by_selector)
	all_blocks: list[str] = []
	if element_body:
		all_blocks.append(element_body)
	if instance_blocks:
		all_blocks.append(instance_blocks)
	if not all_blocks:
		return HEADER
	return HEADER + "\n\n".join(all_blocks) + "\n"


def _table_rows_by_selector() -> dict[str, dict]:
	import frappe

	from themes.utils.design_mode import TABLE_VALUE_FIELDS

	out: dict[str, dict] = {}
	for p in frappe.get_all(
		"Vue Component",
		filters={"status": "Present", "has_table": 1},
		fields=[
			"name",
			"component_name",
			"has_table",
			"table_selector",
			"table_scope_class",
			*TABLE_VALUE_FIELDS,
		],
	):
		sel = (p.get("table_selector") or "").strip()
		if sel and sel not in out:
			out[sel] = dict(p)
	return out


def instance_rule_blocks(records: list[dict], merged_rows: dict[str, dict]) -> list[str]:
	from themes.utils.instance_style import parse_instance_style_overrides

	rule_blocks: list[str] = []
	for rec in records:
		instance_id = (rec.get("instance_id") or "").strip()
		selector = (rec.get("selector_class") or "").strip()
		sparse = parse_instance_style_overrides(rec.get("instance_style_overrides"))
		if not instance_id or not selector or not sparse:
			continue
		component_row = merged_rows.get(selector) or {"selector_class": selector}
		if any(is_table_property_id(k) for k in sparse):
			table_block = table_instance_css_for(component_row, instance_id, sparse)
			if table_block:
				rule_blocks.append(table_block)
			continue
		merged_row = merged_rows.get(selector)
		if merged_row and merged_row.get("keep_default"):
			continue
		blocks = instance_override_declaration_blocks(component_row, sparse)
		if not blocks:
			continue
		prefix = instance_css_selector(selector, instance_id)
		chunk_lines = [f"/* instance › {selector} › {instance_id} */"]
		for pseudo, decls in blocks:
			if not decls:
				continue
			if merged_row and merged_row.get("override_important"):
				decls = _important(decls)
			chunk_lines.append(f"{prefix}{pseudo or ''} {{")
			for decl in decls:
				chunk_lines.append(f"\t{decl}")
			chunk_lines.append("}")
		rule_blocks.append("\n".join(chunk_lines))
	return rule_blocks


def generate_instance_css(rows_by_selector: dict[str, dict]) -> str:
	import frappe

	if not frappe.db.table_exists("Vue Component Instance Style"):
		return ""
	merged_rows = dict(rows_by_selector)
	merged_rows.update(_table_rows_by_selector())
	records = frappe.get_all(
		"Vue Component Instance Style",
		fields=["instance_id", "selector_class", "instance_style_overrides"],
	)
	rule_blocks = instance_rule_blocks(records, merged_rows)
	if not rule_blocks:
		return ""
	return "\n\n".join(rule_blocks)


def _is_button_row(row: dict) -> bool:
	if (row.get("tag") or "").lower() == "button":
		return True
	for token in (row.get("source_classes") or "").split():
		if token.startswith("theme-btn"):
			return True
	return False


def theme_button_rules(rows: list[dict], theme_by_app: dict[str, dict]) -> str:
	from themes.utils.theme_class_catalog import theme_btn_emit_blocks

	if not theme_by_app:
		return ""
	by_key: dict[tuple[str, str], dict] = {}
	for row in rows:
		if row.get("element_status") != "Present":
			continue
		if row.get("keep_default"):
			continue
		app = row.get("app") or ""
		if app not in theme_by_app:
			continue
		selector = (row.get("selector_class") or "").strip()
		if not selector or not SELECTOR_RE.match(selector):
			continue
		if not _is_button_row(row):
			continue
		meta = theme_by_app[app]
		slug = meta["slug"]
		by_key[(slug, selector)] = meta
	if not by_key:
		return ""
	blocks: list[str] = []
	for slug, sel in sorted(by_key.keys()):
		meta = by_key[(slug, sel)]
		payload = meta["payload"]
		base, hover, focus_ring, focus_fill = theme_btn_emit_blocks(payload.get)
		prefix = f'[data-nce-theme="{slug}"] .{sel}'
		chunk_lines = [f"/* theme buttons › {slug} › {sel} */", f":where({prefix}) {{"]
		for decl in base:
			chunk_lines.append(f"\t{decl}")
		chunk_lines.append("}")
		if hover:
			chunk_lines.append(f":where({prefix}:hover:not(:disabled)) {{")
			for decl in hover:
				chunk_lines.append(f"\t{decl}")
			chunk_lines.append("}")
		if focus_ring:
			chunk_lines.append(f":where({prefix}:focus-visible:not(:disabled)) {{")
			for decl in focus_ring:
				chunk_lines.append(f"\t{decl}")
			chunk_lines.append("}")
		if focus_fill:
			chunk_lines.append(f":where({prefix}:focus-visible:not(:disabled)) {{")
			for decl in focus_fill:
				chunk_lines.append(f"\t{decl}")
			chunk_lines.append("}")
		blocks.append("\n".join(chunk_lines))
	return "\n\n".join(blocks)


def publish_component_css() -> dict:
	import frappe

	from themes.component_api import theme_app_slugs, theme_off_apps
	from themes.utils.css_publish import publish_css
	from themes.utils.design_mode import TABLE_VALUE_FIELDS

	off_apps = theme_off_apps()
	_parent_fields = [
		"name",
		"app",
		"component_name",
		"status",
		"has_table",
		"table_selector",
		"table_scope_class",
		"theme_table_targets",
		*TABLE_VALUE_FIELDS,
	]
	parents = {}
	for p in frappe.get_all("Vue Component", fields=_parent_fields):
		name = _row_value(p, "name")
		parents[name] = p
	rows = []
	for r in frappe.get_all("Vue Component Element",
		filters={"parenttype": "Vue Component"},
		fields=["parent", "element_key", "selector_class", "line", "element_status", "keep_default", "override_important", "tag", "source_classes", *OVERRIDE_FIELDS]):
		parent_name = _row_value(r, "parent")
		p = parents.get(parent_name)
		if not p:
			continue
		status = _row_value(p, "status")
		component_name = _row_value(p, "component_name")
		if status != "Present":
			continue
		if (_row_value(p, "app") or "") in off_apps:
			continue
		rows.append({**dict(r), "component_name": component_name, "app": _row_value(p, "app")})
	element_css = generate_component_css(rows)
	theme_by_app: dict[str, dict] = {}
	app_slugs = theme_app_slugs()
	if app_slugs:
		for app, slug in app_slugs.items():
			if app in off_apps:
				continue
			try:
				theme_rows = frappe.get_all(
					"NCE Theme",
					filters={"slug": slug, "status": "Active"},
					fields=["theme_json"],
					limit=1,
				)
				if not theme_rows:
					continue
				payload = json.loads(_row_value(theme_rows[0], "theme_json") or "{}")
			except Exception:
				continue
			theme_by_app[app] = {"slug": slug, "payload": payload}
	button_body = theme_button_rules(rows, theme_by_app)
	sorted_parents = sorted(
		parents.values(),
		key=lambda row: _row_value(row, "component_name") or "",
	)
	bundle_blocks: list[str] = []
	table_blocks: list[str] = []
	for p in sorted_parents:
		status = _row_value(p, "status")
		if status != "Present":
			continue
		if (_row_value(p, "app") or "") in off_apps:
			continue
		parent_dict = dict(p) if isinstance(p, dict) else p.as_dict()
		bundle = theme_table_bundle_for(parent_dict)
		if bundle:
			bundle_blocks.append(bundle)
		block = table_css_for(parent_dict)
		if block:
			table_blocks.append(block)
	body_parts: list[str] = []
	if bundle_blocks:
		body_parts.append("\n\n".join(bundle_blocks))
	if button_body:
		body_parts.append(button_body)
	element_body = element_css[len(HEADER):].strip() if element_css.startswith(HEADER) else element_css.strip()
	if element_body:
		body_parts.append(element_body)
	if table_blocks:
		body_parts.append("\n\n".join(table_blocks))
	css = HEADER + ("\n\n".join(body_parts) + "\n" if body_parts else "")
	css_hash = publish_css("nce_component_overrides.css", css)
	return {"status": "ok", "css_hash": css_hash, "rules": css.count(" › ")}
