"""Generate published CSS for Vue Component colour overrides."""
from __future__ import annotations

from themes.utils.component_sync import (
	BG_RE,
	BORDER_COLOR_RE,
	BORDER_WIDTHS,
	OVERRIDE_FIELDS,
	SELECTOR_RE,
	TEXT_RE,
	has_override,
)

HEADER = "/* Generated by Themes — Vue Component colour overrides. Do not edit; change them in Desk → Vue Component. */\n"


def _row_value(row, key):
	return row.get(key) if isinstance(row, dict) else getattr(row, key, None)


def _valid_text_override(row: dict) -> bool:
	cls = (row.get("override_text_class") or "").strip()
	return bool(cls and TEXT_RE.match(cls))


def declarations_for(row: dict) -> list[str]:
	decls: list[str] = []
	text_override = _valid_text_override(row)

	bg_cls = (row.get("override_bg_class") or "").strip()
	bg_match = BG_RE.match(bg_cls) if bg_cls else None
	if bg_match:
		role, shade = bg_match.group(1), bg_match.group(2)
		v = f"--nce-color-{role}-{shade}" if shade else f"--nce-color-{role}"
		decls.append(f"background-color: var({v});")
		if not text_override:
			fg_suffix = "-fg-tonal" if (row.get("override_fg_type") or "").strip() == "tonal" else "-fg"
			decls.append(f"color: var({v}{fg_suffix});")

	text_cls = (row.get("override_text_class") or "").strip()
	if text_cls and TEXT_RE.match(text_cls):
		rest = text_cls[len("theme-text-"):]
		decls.append(f"color: var(--nce-color-{rest});")

	width_cls = (row.get("override_border_width_class") or "").strip()
	if width_cls in BORDER_WIDTHS:
		decls.append("border-style: solid;")
		decls.append(f"border-width: var({BORDER_WIDTHS[width_cls]});")

	border_cls = (row.get("override_border_color_class") or "").strip()
	border_match = BORDER_COLOR_RE.match(border_cls) if border_cls else None
	if border_match:
		role, shade = border_match.group(1), border_match.group(2)
		decls.append(f"border-color: var(--nce-color-{role}-{shade});")

	return decls


def _table_bg_decls(bg_cls: str, fg_type: str) -> list[str]:
	bg_match = BG_RE.match(bg_cls) if bg_cls else None
	if not bg_match:
		return []
	role, shade = bg_match.group(1), bg_match.group(2)
	v = f"--nce-color-{role}-{shade}" if shade else f"--nce-color-{role}"
	fg_suffix = "-fg-tonal" if fg_type == "tonal" else "-fg"
	return [
		f"background-color: var({v});",
		f"color: var({v}{fg_suffix});",
	]


def _table_border_value(width_cls: str, color_cls: str, default_width_var: str, default_color_var: str) -> str | None:
	width_var = None
	if width_cls in BORDER_WIDTHS:
		width_var = BORDER_WIDTHS[width_cls]
	elif color_cls and BORDER_COLOR_RE.match(color_cls):
		width_var = default_width_var

	color_var = None
	border_match = BORDER_COLOR_RE.match(color_cls) if color_cls else None
	if border_match:
		role, shade = border_match.group(1), border_match.group(2)
		color_var = f"--nce-color-{role}-{shade}"
	elif width_cls in BORDER_WIDTHS:
		color_var = default_color_var

	if not width_var or not color_var:
		return None
	return f"var({width_var}) solid var({color_var})"


def _bundle_selectors(target: str) -> tuple[str, str] | None:
	"""(strong, weak) selector prefixes for one theme_table_targets line."""
	kind, _, name = (target or "").strip().partition(":")
	name = name.strip()
	if not name or not SELECTOR_RE.match(name):
		return None
	if kind == "class":
		return (f".{name}.{name}.{name}", f".{name}")
	if kind == "scope":
		return (f".{name}.{name}.{name} table", f".{name} table")
	return None


def theme_table_bundle_for(parent: dict) -> str:
	"""The theme-table rules, aimed at this component's tables that do not carry theme-table."""
	if (parent.get("status") or "").strip() != "Present":
		return ""
	blocks: list[str] = []
	for line in (parent.get("theme_table_targets") or "").splitlines():
		pair = _bundle_selectors(line)
		if not pair:
			continue
		strong, weak = pair
		col = "var(--nce-border-width-table-col) solid var(--nce-color-table-col-divider)"
		row = "var(--nce-border-width-table-row) solid var(--nce-color-table-row-divider)"
		blocks.append("\n".join([
			f"/* {parent.get('component_name') or ''} › theme table {line.strip()} */",
			f"{strong} {{\n\tborder-collapse: collapse;\n}}",
			f"{strong} thead th, {strong} tfoot th, {strong} tfoot td {{\n\tbackground-color: var(--nce-color-table-header);\n\tcolor: var(--nce-color-table-header-fg, var(--nce-color-text));\n}}",
			f"{weak} tbody tr:nth-child(even) {{\n\tbackground-color: var(--nce-color-row);\n}}",
			f"{weak} tbody tr:nth-child(odd) {{\n\tbackground-color: var(--nce-color-row-alt);\n}}",
			f"{strong} td {{\n\tborder-bottom: {row};\n\tborder-right: {col};\n}}",
			f"{strong} th {{\n\tborder-right: {col};\n}}",
			f"{strong} th:last-child, {strong} td:last-child {{\n\tborder-right: none;\n}}",
		]))
	return "\n\n".join(blocks)


def _table_prefix(parent: dict) -> str | None:
	sel = (parent.get("table_selector") or "").strip()
	scope = (parent.get("table_scope_class") or "").strip()
	if not sel or not SELECTOR_RE.match(sel):
		return None
	if scope and not SELECTOR_RE.match(scope):
		return None
	if scope:
		return f".{scope}.{scope}.{scope} .{sel}"
	return f".{sel}.{sel}.{sel}"


def table_css_for(parent: dict) -> str:
	if (parent.get("status") or "").strip() != "Present":
		return ""
	if not int(parent.get("has_table") or 0):
		return ""
	prefix = _table_prefix(parent)
	if not prefix:
		return ""

	component_name = parent.get("component_name") or ""
	sel = (parent.get("table_selector") or "").strip()
	scope = (parent.get("table_scope_class") or "").strip()
	row_prefix = f".{scope} .{sel}" if scope else f".{sel}"
	rules: list[str] = []

	header_bg = (parent.get("table_header_bg_class") or "").strip()
	header_fg = (parent.get("table_header_fg_type") or "mono").strip() or "mono"
	header_decls = _table_bg_decls(header_bg, header_fg)
	if header_decls:
		target = f"{prefix} thead th, {prefix} tfoot th, {prefix} tfoot td"
		rules.append(target + " {\n\t" + "\n\t".join(header_decls) + "\n}")

	row_bg = (parent.get("table_row_bg_class") or "").strip()
	row_fg = (parent.get("table_row_fg_type") or "mono").strip() or "mono"
	row_decls = _table_bg_decls(row_bg, row_fg)
	if row_decls:
		target = f"{row_prefix} tbody tr:nth-child(even)"
		rules.append(target + " {\n\t" + "\n\t".join(row_decls) + "\n}")

	alt_bg = (parent.get("table_row_alt_bg_class") or "").strip()
	alt_fg = (parent.get("table_row_alt_fg_type") or "mono").strip() or "mono"
	alt_decls = _table_bg_decls(alt_bg, alt_fg)
	if alt_decls:
		target = f"{row_prefix} tbody tr:nth-child(odd)"
		rules.append(target + " {\n\t" + "\n\t".join(alt_decls) + "\n}")

	header_line_w = (parent.get("table_header_line_class") or "").strip()
	header_line_c = (parent.get("table_header_line_color_class") or "").strip()
	header_border = _table_border_value(
		header_line_w,
		header_line_c,
		"--nce-border-width-table-row",
		"--nce-color-table-row-divider",
	)
	if header_border:
		rules.append(f"{prefix} thead th {{\n\tborder-bottom: {header_border};\n}}")

	row_div_w = (parent.get("table_row_divider_class") or "").strip()
	row_div_c = (parent.get("table_row_divider_color_class") or "").strip()
	row_border = _table_border_value(
		row_div_w,
		row_div_c,
		"--nce-border-width-table-row",
		"--nce-color-table-row-divider",
	)
	if row_border:
		rules.append(f"{prefix} td {{\n\tborder-bottom: {row_border};\n}}")

	col_div_w = (parent.get("table_col_divider_class") or "").strip()
	col_div_c = (parent.get("table_col_divider_color_class") or "").strip()
	col_border = _table_border_value(
		col_div_w,
		col_div_c,
		"--nce-border-width-table-col",
		"--nce-color-table-col-divider",
	)
	if col_border:
		rules.append(f"{prefix} th, {prefix} td {{\n\tborder-right: {col_border};\n}}")
		rules.append(
			f"{prefix} th:last-child, {prefix} td:last-child {{\n\tborder-right: none;\n}}"
		)

	if not rules:
		return ""
	return f"/* {component_name} › table {sel} */\n" + "\n\n".join(rules)


def generate_component_css(rows: list[dict]) -> str:
	eligible: list[dict] = []
	for row in rows:
		if row.get("element_status") != "Present":
			continue
		if row.get("keep_default"):
			continue
		selector = (row.get("selector_class") or "").strip()
		if not SELECTOR_RE.match(selector):
			continue
		if not has_override(row):
			continue
		eligible.append(row)

	by_rule: dict[tuple[str, str], dict] = {}
	for row in eligible:
		key = (row.get("component_name") or "", (row.get("selector_class") or "").strip())
		if key not in by_rule or int(row.get("line") or 0) < int(by_rule[key].get("line") or 0):
			by_rule[key] = row

	sorted_rows = sorted(by_rule.values(), key=lambda r: (r.get("component_name") or "", (r.get("selector_class") or "").strip()))
	rule_blocks: list[str] = []
	for row in sorted_rows:
		decls = declarations_for(row)
		if not decls:
			continue
		c = (row.get("selector_class") or "").strip()
		component_name = row.get("component_name") or ""
		lines = [f"/* {component_name} › {c} */", f".{c}.{c}.{c} {{"]
		for decl in decls:
			lines.append(f"\t{decl}")
		lines.append("}")
		rule_blocks.append("\n".join(lines))

	if not rule_blocks:
		return HEADER
	return HEADER + "\n\n".join(rule_blocks) + "\n"


def publish_component_css() -> dict:
	import frappe

	from themes.component_api import theme_off_apps
	from themes.utils.css_publish import publish_css
	from themes.utils.design_mode import TABLE_VALUE_FIELDS

	off_apps = theme_off_apps()
	_parent_fields = [
		"name",
		"app",
		"component_name",
		"status",
		"has_table",
		"table_selector",
		"table_scope_class",
		"theme_table_targets",
		*TABLE_VALUE_FIELDS,
	]
	parents = {}
	for p in frappe.get_all("Vue Component", fields=_parent_fields):
		name = _row_value(p, "name")
		parents[name] = p
	rows = []
	for r in frappe.get_all("Vue Component Element",
		filters={"parenttype": "Vue Component"},
		fields=["parent", "element_key", "selector_class", "line", "element_status", "keep_default", *OVERRIDE_FIELDS]):
		parent_name = _row_value(r, "parent")
		p = parents.get(parent_name)
		if not p:
			continue
		status = _row_value(p, "status")
		component_name = _row_value(p, "component_name")
		if status != "Present":
			continue
		if (_row_value(p, "app") or "") in off_apps:
			continue
		rows.append({**dict(r), "component_name": component_name})
	element_css = generate_component_css(rows)
	sorted_parents = sorted(
		parents.values(),
		key=lambda row: _row_value(row, "component_name") or "",
	)
	bundle_blocks: list[str] = []
	table_blocks: list[str] = []
	for p in sorted_parents:
		status = _row_value(p, "status")
		if status != "Present":
			continue
		if (_row_value(p, "app") or "") in off_apps:
			continue
		parent_dict = dict(p) if isinstance(p, dict) else p.as_dict()
		bundle = theme_table_bundle_for(parent_dict)
		if bundle:
			bundle_blocks.append(bundle)
		block = table_css_for(parent_dict)
		if block:
			table_blocks.append(block)
	body_parts: list[str] = []
	if bundle_blocks:
		body_parts.append("\n\n".join(bundle_blocks))
	element_body = element_css[len(HEADER):].strip() if element_css.startswith(HEADER) else element_css.strip()
	if element_body:
		body_parts.append(element_body)
	if table_blocks:
		body_parts.append("\n\n".join(table_blocks))
	css = HEADER + ("\n\n".join(body_parts) + "\n" if body_parts else "")
	css_hash = publish_css("nce_component_overrides.css", css)
	return {"status": "ok", "css_hash": css_hash, "rules": css.count(" › ")}
